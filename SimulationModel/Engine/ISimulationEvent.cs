namespace Simulation.Engine;

/// <summary>
/// Интерфейс события имитационной модели.
/// Событие имеет абсолютное модельное время наступления, приоритет для детерминированного
/// упорядочивания при совпадении времени и логику выполнения.
/// </summary>
public interface ISimulationEvent
{
    /// <summary>
    /// Абсолютное модельное время наступления события.
    /// </summary>
    double Time { get; }

    /// <summary>
    /// Приоритет события (меньшее число - выше приоритет).
    /// Используется для разрешения коллизий при одновременных событиях.
    /// </summary>
    int Priority { get; }

    /// <summary>
    /// Название или тип события для трассировки.
    /// </summary>
    string Name { get; }

    /// <summary>
    /// Выполнение логики события в контексте симулятора.
    /// </summary>
    void Execute(Simulator simulator);
}
